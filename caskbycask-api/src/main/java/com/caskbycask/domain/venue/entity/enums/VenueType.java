package com.caskbycask.domain.venue.entity.enums;

/**
 * 주류 장소 유형.
 *
 * <p>일부러 셋만 둔다. 유형은 <b>"거기서 무엇을 할 수 있는가"</b>를 나눠야 필터가 쓸모 있다 —
 * "누가 운영하는가"나 "어떤 술이 주력인가"로 나누기 시작하면 칩이 늘어나고, 같은 곳을 찾는
 * 사람이 여러 칩을 번갈아 누르게 된다.
 *
 * <p>그래서 몰트바는 {@link #BAR} 에, 면세점은 {@link #BOTTLE_SHOP} 에 합쳤다(V107).
 * 위스키 라인업이 주력이라거나 증류소 병설이라는 사실은 이름·소개가 전달한다.
 */
public enum VenueType {
    /** 마시는 곳 — 바·몰트바·위스키바를 아우른다. */
    BAR,
    /** 사 가는 곳 — 리쿼샵·보틀샵·면세점처럼 병으로 파는 매장. 화면 라벨은 "리쿼샵". */
    BOTTLE_SHOP,
    /** 그 외 — 레스토랑·호텔 바처럼 위 둘로 딱 떨어지지 않는 곳. */
    OTHER
}
