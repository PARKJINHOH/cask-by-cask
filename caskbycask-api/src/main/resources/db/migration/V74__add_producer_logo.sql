-- =============================================================================
-- 생산자(증류소/와이너리/꼬냑하우스)에 로고 이미지 추가
-- =============================================================================
-- 포토카드에 증류소 로고를 얹기 위해 필요하다. producer 테이블에는 지금까지
-- 이미지 컬럼이 하나도 없었다.
--
-- URL 만이 아니라 saved_file_name/sub_path 를 함께 저장하는 이유:
-- 저장 경로가 'producers/202608' 처럼 연월 디렉토리라 URL 만으로는 삭제·교체 시
-- 원본 파일 위치를 복원할 수 없다(프로필 이미지는 subPath 가 고정이라 URL 파싱으로 됐다).
--
-- ※ producer 는 Hibernate Search @Indexed 대상이지만, 로고 컬럼에는 검색 애노테이션을
--    붙이지 않으므로 인덱스 스키마가 바뀌지 않는다(재색인 불필요).
-- =============================================================================

ALTER TABLE producer
    ADD COLUMN logo_image_url       varchar(500) comment '로고 이미지 URL',
    ADD COLUMN logo_saved_file_name varchar(255) comment '로고 저장 파일명',
    ADD COLUMN logo_sub_path        varchar(200) comment '로고 저장 하위 경로';
