-- =============================================================================
-- 게시글 이미지에 원본 크기(width/height) 저장
-- =============================================================================
-- 이미지 갤러리 목록은 justified 그리드(사진 비율대로 행을 꽉 채우는 배치)다.
-- 행 높이를 계산하려면 배치 전에 각 사진의 가로/세로 비율을 알아야 하는데,
-- 지금은 이미지 URL 만 있어 브라우저가 다운로드를 마쳐야 비율을 알 수 있다.
-- → 목록이 로드되며 레이아웃이 계속 튀게 되므로 업로드 시점에 크기를 저장한다.
--
-- nullable 인 이유: 기존 이미지 수만 건은 파일을 전부 열어야 백필할 수 있어
-- 마이그레이션에서 채우지 않는다. 프론트가 img.onLoad 의 naturalWidth/Height 로
-- 보정하는 폴백을 갖는다.
-- =============================================================================

ALTER TABLE post_images
    ADD COLUMN width  integer comment '이미지 가로(px)',
    ADD COLUMN height integer comment '이미지 세로(px)';
