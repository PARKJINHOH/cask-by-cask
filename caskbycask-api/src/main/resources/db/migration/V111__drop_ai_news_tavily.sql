-- 소식(AI): Tavily 제거. 수집은 등록 출처 직접 확인 하나로 줄인다.
--
-- 배경
--  - 근거 수집은 두 경로였다. ① 관리자가 등록한 출처 URL 직접 확인 ② 등록 도메인으로 가둔 Tavily 제한 검색.
--    ②를 운영해 보니 쓸 만한 소재를 물어오지 않아 크레딧만 나갔다. 그래서 ①만 남겼다.
--  - 그러면 이 두 컬럼은 아무도 쓰지 않는다. 월 크레딧 한도는 존재하지 않는 호출을 막는 설정이 되고,
--    사용량의 크레딧 칸은 영원히 0 이다. 관리자 화면에 남겨 두면 끄고 켤 수 있는 것처럼 보여 더 나쁘다.

-- 1) 월 크레딧 한도. 관리자 설정 화면의 입력칸도 함께 사라진다.
alter table ai_news_settings drop column tavily_monthly_credit_limit;

-- 2) 실행별 크레딧 사용량.
--    provider = 'TAVILY' 행 자체는 지우지 않는다 — 지난달 사용량 집계의 근거이고,
--    크롤러가 더는 만들지 않으므로 그대로 두면 옛 이력으로 남는다.
alter table ai_news_usage drop column tavily_credits;
