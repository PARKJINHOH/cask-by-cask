-- =============================================================================
-- 생산자 검색 별칭(search_keywords) 컬럼 추가
-- =============================================================================
-- 목적: 한글 음차 표기 변형(예: DB '카뮈' ↔ 통용 '까뮤')으로 검색이 안 되는 문제 해결.
--       표시 이름(name_ko/name_en)은 그대로 두고, 별칭만 검색에 포함한다.
--       공개 술 검색은 생산자명/별칭까지 매칭하므로, 생산자에 별칭을 넣으면
--       해당 생산자의 모든 술이 별칭으로도 검색된다.
-- =============================================================================

ALTER TABLE producer ADD COLUMN search_keywords VARCHAR(300) NULL COMMENT '검색 별칭(공백/콤마 구분)';

-- 카뮈(Camus) — 국내 통용 표기 '까뮤'로도 검색되도록 별칭 부여
UPDATE producer
   SET search_keywords = '까뮤 까뮈 Camus'
 WHERE name_en = 'Camus';
